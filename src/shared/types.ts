// Domain types shared by the service, the guests and the tests.
// Shapes follow docs/SPEC.md §6 (on-disk contract) and §7 (what the service answers).
// Types plus identity constants only: no logic, no imports from the SDK.

/** Plain JSON: what survives `JSON.stringify` / `JSON.parse` unchanged. */
export type JsonValue = string | number | boolean | null | JsonValue[] | JsonObject;
export type JsonObject = { [key: string]: JsonValue };

/** ISO-8601 timestamp string (`2026-10-26T18:00:00.000Z`). */
export type IsoDate = string;

/** `page` = one `index.html` shown full screen; `canvas` = a wall of screens. Older files saying `artifact` read as `page` (`normalizeKind`). */
export type DesignKind = 'page' | 'canvas';

// ---- design.json [§6.2] ----

export type Viewport = {
  /** `VIEWPORT_ID_PATTERN`, unique within the design. */
  id: string;
  /** 1..`VIEWPORT_LABEL_MAX`; defaults to the id. */
  label: string;
  /** CSS px, integer `VIEWPORT_WIDTH_MIN..MAX`. */
  width: number;
  /** CSS px, integer `VIEWPORT_HEIGHT_MIN..MAX`. */
  height: number;
};

export type Screen = {
  /** `SCREEN_ID_PATTERN`, unique within the design. */
  id: string;
  /** 1..`TITLE_MAX`; defaults to the id. */
  title: string;
  /** Always `screens/<id>.html` with `/` separators. */
  file: string;
  /** Subset of the design's viewport ids; absent = every viewport. */
  viewports?: string[];
  /** ≤ `SCREEN_DESCRIPTION_MAX`. */
  description?: string;
  /** Marks this screen as a direction of another screen (Phase 2 §6.1); absent on a normal screen. */
  direction?: DirectionMark;
};

/** A direction's letter within its group: four letters cap a group at 4 directions. */
export type DirectionLetter = 'A' | 'B' | 'C' | 'D';

/** Agent-written mark on a screen entry: this screen is direction `letter` of screen `of` (Phase 2 §6.1). */
export type DirectionMark = { of: string; letter: DirectionLetter; name: string };

/** A number knob: a slider over one custom property in tokens.css (Phase 2 §4.1). */
export type TweakNumber = { var: string; label: string; kind: 'number'; min: number; max: number; step: number; unit: string };
/** A choice knob: 2 to 6 named plain values for one custom property (Phase 2 §4.1). */
export type TweakChoice = { var: string; label: string; kind: 'choice'; options: { label: string; value: string }[] };
export type Tweak = TweakNumber | TweakChoice;

export type DesignSystemStatus = {
  /** The agent sets true once the user confirmed DESIGN.md / tokens.css. */
  confirmed: boolean;
};

/** Document px rectangle. */
export type Rect = { x: number; y: number; w: number; h: number };
/** Relative pin offset inside an anchor rect, each axis 0..1. */
export type RelPoint = { x: number; y: number };

export type CommentAnchor = {
  /** CSS selector generated by the bridge (`selector.ts`), ≤ `ANCHOR_SELECTOR_MAX`. */
  selector: string;
  /** Normalised element text, ≤ `ANCHOR_TEXT_MAX`. */
  text: string;
  /** Opening tag snippet, ≤ `ANCHOR_HTML_MAX`. */
  html: string;
  /** Element rect in document px at capture time. */
  rect: Rect;
  /** Where the pin sits inside `rect`. */
  point: RelPoint;
};

export type CommentStatus = 'open' | 'sent' | 'resolved';

/** How the page found a comment's element in the current file (`moved` = matched by text, `detached` = not found). */
export type AnchorState = 'exact' | 'moved' | 'detached';

export type Comment = {
  /** `COMMENT_ID_PATTERN`. */
  id: string;
  /** Screen id on a canvas; `null` on a page. */
  screen: string | null;
  /** Viewport id the comment was made on; on a page also `PAGE_FILL_VIEWPORT_ID` (the Full-width view). */
  viewport: string;
  anchor: CommentAnchor;
  /** 1..`COMMENT_BODY_MAX`. */
  body: string;
  status: CommentStatus;
  created: IsoDate;
  sentAt: IsoDate | null;
  /** Version number (`n`) current when the comment was sent. */
  sentVersion: number | null;
};

/**
 * The normalised read view of `design.json` (schema `design-chamber/design@1`).
 * Unknown top-level keys are not here — they travel separately as `extra` and are
 * never lost on write (see `design-json.ts`).
 */
export type DesignJson = {
  version: 1;
  kind: DesignKind;
  title: string;
  created: IsoDate;
  updated: IsoDate;
  /** ≤ `BRIEF_MAX`; empty string when none. */
  brief: string;
  sessionId: string | null;
  projectDirectory: string | null;
  preset: string | null;
  /** `index.html` for a page, `null` for a canvas. */
  entry: string | null;
  /** 1..`VIEWPORTS_MAX`, ids unique. */
  viewports: Viewport[];
  /** Canvas: 0..`SCREENS_MAX` in wall row order. Page: always `[]`. */
  screens: Screen[];
  designSystem: DesignSystemStatus;
  /** Tweaks knobs for the panel (Phase 2 §4.1); `[]` when absent. */
  tweaks: Tweak[];
  /**
   * The agent's recorded design-system choice (Phase 2.5 §2.7): a system id or `"none"`.
   * Agent-owned; the service never writes it. Absent on old designs and until the agent
   * records an answer; an invalid value is dropped with an `invalid-system-choice` warning.
   */
  systemChoice?: string;
  /**
   * The agent's filing request (Phase 2.6 AD-16): folder names to tag or untag, acted on once
   * by the service. Agent-owned; unknown names warn, never create. Absent on old designs.
   */
  folderRequest?: FolderRequest;
  comments: Comment[];
};

/** Fields the service owns; truth is `.chamber/state.json`, design.json carries a mirror [§6.3]. */
export type ServiceOwnedField =
  | 'version'
  | 'kind'
  | 'created'
  | 'brief'
  | 'sessionId'
  | 'projectDirectory'
  | 'preset'
  | 'entry'
  | 'comments';

/**
 * Fields the agent owns; read from design.json only [§6.3]. `title` is also written on a user
 * rename; `screens` is shared — the service writes it for the user's screen actions and the
 * agent's later write wins (Phase 2 §5.1).
 */
export type AgentOwnedField = 'title' | 'updated' | 'viewports' | 'screens' | 'designSystem' | 'tweaks' | 'systemChoice' | 'folderRequest';

/**
 * `.chamber/state.json` — authoritative service-owned fields [§6.3].
 * `provisional: true` marks a state seeded from files before the agent's design.json
 * landed; it is adopted from design.json once that parses, and is never mirrored into
 * design.json. Absent = final.
 *
 * The Phase 2.5 system fields (§2.7) are service-owned too: never mirrored into
 * design.json, never adopted from it, never versioned.
 */
export type ServiceState = Pick<DesignJson, Exclude<ServiceOwnedField, 'version'>> & {
  version: 1;
  provisional?: true;
  /**
   * The design's system decision: `ask` until answered, `none` or `system` after a link action, `project` when it
   * was made to follow its project's own design files (use-the-project spec §1.4; written once at creation).
   */
  systemDecision?: 'ask' | 'none' | 'system' | 'project';
  /** The last design.json `systemChoice` value the service acted on (an id or `"none"`). */
  systemChoiceSeen?: string;
  /** Why the agent's recorded choice could not be acted on. */
  systemChoiceProblem?: SystemChoiceProblem;
  /** The last design.json `folderRequest` stamp the service acted on (Phase 2.6 AD-16). */
  folderRequestSeen?: string;
  /**
   * Folder names in a `folderRequest` that do not exist; never created. `waiting`: the request waits for a
   * retry; `reason: 'write'` when the registry write failed (busy, disk full), absent when it couldn't load.
   */
  folderRequestProblem?: { unknown: string[]; waiting?: true; reason?: 'write' };
};

/** A `systemChoice` the service could not act on (Phase 2.5 §2.7); `value` is the raw agent text, ≤ 80 chars. */
export type SystemChoiceProblem = {
  value: string;
  reason: 'unknown' | 'draft' | 'being-changed' | 'too-large' | 'failed';
};

/** One problem found while reading agent-written data. Never fatal. */
export type DesignWarning = {
  /** Stable machine code, e.g. `invalid-viewport`, `no-design-json`. */
  code: string;
  /** JSON path of the offending value (`viewports[2].width`), when there is one. */
  field?: string;
  /** User-facing sentence. */
  message: string;
};

// ---- .versions/ [§6.4] ----

/**
 * `manual` is the user's "Snapshot now" (SPEC §14 "WP0 deviations"); `user-edit` and `keep-direction` are the hand-edit versions (Phase 2 §2.1).
 * Phase 2.5: `resync` ("Before re-sync"), `system-change` / `system-update` (a design's copy-on-link / update, §5.4),
 * `repo-read` ("Before reading shop", an agent-triggered snapshot refresh, §5.2).
 */
export type VersionReason =
  | 'auto' | 'turn' | 'manual' | 'restore-point' | 'restored' | 'user-edit' | 'keep-direction'
  | 'resync' | 'system-change' | 'system-update' | 'repo-read';

export type VersionEntry = {
  /** `v<n>`. */
  id: string;
  n: number;
  created: IsoDate;
  reason: VersionReason;
  sessionId: string | null;
  /** sha256 over the tracked file set. */
  treeHash: string;
  /** Tracked relative path (`/` separators) → sha256 of its bytes. */
  files: Record<string, string>;
  /** Sum of tracked file sizes. */
  bytes: number;
  label?: string;
};

/** What routes answer: a version without its file map. */
export type VersionSummary = Omit<VersionEntry, 'files'> & { fileCount: number };

/** `.versions/index.json`. Newest last. */
export type VersionIndex = {
  version: 1;
  next: number;
  versions: VersionEntry[];
};

export type VersionFileChange = 'added' | 'removed' | 'modified';

