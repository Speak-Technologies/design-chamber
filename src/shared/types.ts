// Domain types shared by the service, the guests and the tests.
// Shapes follow docs/SPEC.md §6 (on-disk contract) and §7 (what the service answers).
// Types plus identity constants only: no logic, no imports from the SDK.

/** Plain JSON: what survives `JSON.stringify` / `JSON.parse` unchanged. */
export type JsonValue = string | number | boolean | null | JsonValue[] | JsonObject;
export type JsonObject = { [key: string]: JsonValue };

/** ISO-8601 timestamp string (`2026-10-26T18:00:00.000Z`). */
export type IsoDate = string;

/** `page` = one `index.html` shown full screen; `canvas` = a wall of screens. Older files saying `artifact` read as `page` (`normalizeKind`). */
export type DesignKind = 'page' | 'canvas';

// ---- design.json [§6.2] ----

export type Viewport = {
  /** `VIEWPORT_ID_PATTERN`, unique within the design. */
  id: string;
  /** 1..`VIEWPORT_LABEL_MAX`; defaults to the id. */
  label: string;
  /** CSS px, integer `VIEWPORT_WIDTH_MIN..MAX`. */
  width: number;
  /** CSS px, integer `VIEWPORT_HEIGHT_MIN..MAX`. */
  height: number;
};

export type Screen = {
  /** `SCREEN_ID_PATTERN`, unique within the design. */
  id: string;
  /** 1..`TITLE_MAX`; defaults to the id. */
  title: string;
  /** Always `screens/<id>.html` with `/` separators. */
  file: string;
  /** Subset of the design's viewport ids; absent = every viewport. */
  viewports?: string[];
  /** ≤ `SCREEN_DESCRIPTION_MAX`. */
  description?: string;
};

export type DesignSystemStatus = {
  /** The agent sets true once the user confirmed DESIGN.md / tokens.css. */
  confirmed: boolean;
};

/** Document px rectangle. */
export type Rect = { x: number; y: number; w: number; h: number };
/** Relative pin offset inside an anchor rect, each axis 0..1. */
export type RelPoint = { x: number; y: number };

export type CommentAnchor = {
  /** CSS selector generated by the bridge (`selector.ts`), ≤ `ANCHOR_SELECTOR_MAX`. */
  selector: string;
  /** Normalised element text, ≤ `ANCHOR_TEXT_MAX`. */
  text: string;
  /** Opening tag snippet, ≤ `ANCHOR_HTML_MAX`. */
  html: string;
  /** Element rect in document px at capture time. */
  rect: Rect;
  /** Where the pin sits inside `rect`. */
  point: RelPoint;
};

export type CommentStatus = 'open' | 'sent' | 'resolved';

/** How the page found a comment's element in the current file (`moved` = matched by text, `detached` = not found). */
export type AnchorState = 'exact' | 'moved' | 'detached';

export type Comment = {
  /** `COMMENT_ID_PATTERN`. */
  id: string;
  /** Screen id on a canvas; `null` on a page. */
  screen: string | null;
  /** Viewport id the comment was made on; on a page also `PAGE_FILL_VIEWPORT_ID` (the Full-width view). */
  viewport: string;
  anchor: CommentAnchor;
  /** 1..`COMMENT_BODY_MAX`. */
  body: string;
  status: CommentStatus;
  created: IsoDate;
  sentAt: IsoDate | null;
  /** Version number (`n`) current when the comment was sent. */
  sentVersion: number | null;
};

/**
 * The normalised read view of `design.json` (schema `design-chamber/design@1`).
 * Unknown top-level keys are not here — they travel separately as `extra` and are
 * never lost on write (see `design-json.ts`).
 */
export type DesignJson = {
  version: 1;
  kind: DesignKind;
  title: string;
  created: IsoDate;
  updated: IsoDate;
  /** ≤ `BRIEF_MAX`; empty string when none. */
  brief: string;
  sessionId: string | null;
  projectDirectory: string | null;
  preset: string | null;
  /** `index.html` for a page, `null` for a canvas. */
  entry: string | null;
  /** 1..`VIEWPORTS_MAX`, ids unique. */
  viewports: Viewport[];
  /** Canvas: 0..`SCREENS_MAX` in wall row order. Page: always `[]`. */
  screens: Screen[];
  designSystem: DesignSystemStatus;
  comments: Comment[];
};

/** Fields the service owns; truth is `.chamber/state.json`, design.json carries a mirror [§6.3]. */
export type ServiceOwnedField =
  | 'version'
  | 'kind'
  | 'created'
  | 'brief'
  | 'sessionId'
  | 'projectDirectory'
  | 'preset'
  | 'entry'
  | 'comments';

/** Fields the agent owns; read from design.json only [§6.3]. `title` is also written on a user rename. */
export type AgentOwnedField = 'title' | 'updated' | 'viewports' | 'screens' | 'designSystem';

/**
 * `.chamber/state.json` — authoritative service-owned fields [§6.3].
 * `provisional: true` marks a state seeded from files before the agent's design.json
 * landed; it is adopted from design.json once that parses, and is never mirrored into
 * design.json. Absent = final.
 */
export type ServiceState = Pick<DesignJson, Exclude<ServiceOwnedField, 'version'>> & { version: 1; provisional?: true };

/** One problem found while reading agent-written data. Never fatal. */
export type DesignWarning = {
  /** Stable machine code, e.g. `invalid-viewport`, `no-design-json`. */
  code: string;
  /** JSON path of the offending value (`viewports[2].width`), when there is one. */
  field?: string;
  /** User-facing sentence. */
  message: string;
};

// ---- .versions/ [§6.4] ----

/** `manual` is the user's "Snapshot now" (SPEC §14 "WP0 deviations"). */
export type VersionReason = 'auto' | 'turn' | 'manual' | 'restore-point' | 'restored';

export type VersionEntry = {
  /** `v<n>`. */
  id: string;
  n: number;
  created: IsoDate;
  reason: VersionReason;
  sessionId: string | null;
  /** sha256 over the tracked file set. */
  treeHash: string;
  /** Tracked relative path (`/` separators) → sha256 of its bytes. */
  files: Record<string, string>;
  /** Sum of tracked file sizes. */
  bytes: number;
  label?: string;
};

/** What routes answer: a version without its file map. */
export type VersionSummary = Omit<VersionEntry, 'files'> & { fileCount: number };

/** `.versions/index.json`. Newest last. */
export type VersionIndex = {
  version: 1;
  next: number;
  versions: VersionEntry[];
};

export type VersionFileChange = 'added' | 'removed' | 'modified';

// ---- Settings [§6.5] ----

/** The service-owned settings file. Every key but `version` optional. */
export type SettingsFile = {
  version: 1;
  root?: string;
  /** ≤ `PREVIOUS_ROOTS_MAX`, newest first. */
  previousRoots?: string[];
  chromePath?: string;
  downloadsDir?: string;
};

export type BrowserSource = 'setting' | 'detected' | 'none';

// ---- Change hub [§7, §9.4] ----

/** `loose`: the set of loose `.html`/`.htm` files directly in the root changed (slug `null`). */
export type ChangeKind = 'added' | 'removed' | 'design' | 'files' | 'thumb' | 'versions' | 'comments' | 'root' | 'loose' | 'checks';

export type ChangeEvent = {
  seq: number;
  /** `null` for root-wide events (`root`, `loose`). */
  slug: string | null;
  kind: ChangeKind;
  /** Relative paths inside the design (`/` separators) for `files` events. */
  files?: string[];
};

// ---- Summaries and records [§7] ----

export type ThumbState = 'ready' | 'pending' | 'unavailable' | 'failed';

export type DesignSummary = {
  slug: string;
  kind: DesignKind;
  title: string;
  created: IsoDate;
  updated: IsoDate;
  /** No entry/screen file exists yet ("Waiting for agent"). */
  pending: boolean;
  screenCount: number;
  viewports: Viewport[];
  sessionId: string | null;
  openComments: number;
  thumb: { state: ThumbState; key: string | null };
  warnings: DesignWarning[];
};

export type FileStatus = { exists: boolean; size: number; mtime: IsoDate | null };

export type DesignFiles = {
  /** Page entry (`index.html`); absent on a canvas. */
  entry?: FileStatus;
  /** Canvas screen id → its file status. Empty on a page. */
  screens: Record<string, FileStatus>;
};

/** A loose `.html`/`.htm` file directly in the designs root: not a design, offered for import. */
export type LooseHtmlFile = { name: string; bytes: number; mtime: IsoDate };

// ---- Agent discovery: guide and skill ----

/** `<root>/AGENTS.md`, kept by the service while it is ours and unedited. */
export type GuideState = 'current' | 'outdated' | 'edited' | 'foreign' | 'missing' | 'no-root' | 'failed';
export type AgentGuideStatus = {
  /** Absolute path of the guide file. */
  path: string;
  state: GuideState;
  /** User-facing sentence, e.g. the reason for `failed`. */
  message?: string;
};

/** The `design-chamber` OpenCode skill, installed only on the user's click. */
export type SkillState = 'not-installed' | 'current' | 'outdated' | 'edited' | 'foreign' | 'unavailable';
export type AgentSkillStatus = {
  /** Absolute path of `SKILL.md` (real path of its folder when it exists). */
  path: string;
  state: SkillState;
  /** Other `design-chamber/SKILL.md` copies OpenCode would also load. */
  duplicates: string[];
  /** User-facing sentence, e.g. the reason for `unavailable`. */
  message?: string;
};

// ---- Design checks (documentation/specs/agent-render-and-check.md §2.2) ----

/** Closed set: a finding on disk can only name one of these; its severity and sentence come from `src/shared/checks.ts`. */
export type CheckCode =
  // rendering
  | 'overflow-x'
  | 'text-clipped'
  | 'text-overlap'
  | 'contrast'
  | 'img-alt'
  | 'control-label'
  | 'button-name'
  | 'screen-tall'
  | 'page-height'
  | 'console-error'
  | 'request-blocked'
  | 'dialog-opened'
  | 'render-failed'
  | 'render-timeout'
  | 'render-skipped'
  | 'browser-missing'
  // files
  | 'design-json-missing'
  | 'design-json-invalid'
  | 'design-json-field'
  | 'screen-file-missing'
  | 'screen-unlisted'
  | 'screen-per-viewport'
  | 'entry-missing'
  | 'ref-missing'
  | 'ref-outside'
  | 'remote-ref'
  | 'module-import'
  | 'doc-doctype'
  | 'doc-lang'
  | 'doc-viewport'
  | 'doc-title'
  | 'doc-charset'
  | 'token-redefined'
  | 'token-hardcoded'
  | 'check-partial';

export type CheckSeverity = 'error' | 'warning' | 'info';

/** Numbers, or ids matching their patterns: the only values a message sentence is filled from. */
export type CheckParams = {
  px?: number;
  width?: number;
  ratio?: number;
  min?: number;
  count?: number;
  max?: number;
  field?: string;
  base?: string;
  /** `render-skipped` only: why the artboards were not rendered. */
  reason?: 'limit' | 'budget' | 'failures';
};

/** A finding as `check.json` stores it. `detail` and `selector` are untrusted design text. */
export type CheckFindingData = {
  code: CheckCode;
  /** Design-relative path with `/` separators. */
  file: string | null;
  screen: string | null;
  viewport: string | null;
  params?: CheckParams;
  /** ≤ `CHECK_DETAIL_MAX`, one line, untrusted. */
  detail?: string;
  /** ≤ `CHECK_SELECTOR_MAX`, one line, untrusted. */
  selector?: string;
};

/** What the service answers: the stored finding plus the severity and sentence it derives from `code`. */
export type CheckFinding = CheckFindingData & { severity: CheckSeverity; message: string };

export type CheckBrowser = 'chrome' | 'msedge' | 'chromium' | 'brave' | 'other';

/** `done` = every planned artboard rendered; `partial` = some were skipped or failed; `unavailable` = no browser. */
export type RenderCheckState = 'done' | 'partial' | 'unavailable' | 'failed';

export type ArtboardCheck = {
  /** Screen id on a canvas; `null` for a page. */
  screen: string | null;
  viewport: string;
  width: number;
  height: number;
  docHeight: number;
  /** `.chamber/check/r-<runId>/<name>.png`, design-relative. */
  pngs: string[];
  ok: boolean;
  ms: number;
};

/** `<design>/.chamber/check.json` (schema `design-chamber/check@1`). */
export type CheckReport = {
  version: 1;
  slug: string;
  kind: DesignKind;
  createdAt: IsoDate;
  tool: 'cli' | 'service';
  static: { findings: CheckFindingData[] };
  render: {
    state: RenderCheckState;
    /** Basename class of the browser, never a path. */
    browser: CheckBrowser | null;
    keys: { design: string; entries: Record<string, string> };
    artboards: ArtboardCheck[];
    skipped: number;
    findings: CheckFindingData[];
  } | null;
};

